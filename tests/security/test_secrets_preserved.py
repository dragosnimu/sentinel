def test_a_rotation_run_keeps_every_key_the_host_already_had(tmp_path):
    """The reported failure: `--force-step 22,27` deleted SENTINEL_BEACON_SECRET.

    Eight keys on disk, five supplied on stdin, one of them rotated. All eight
    must survive; only the rotated one may change. Lose the beacon key and the
    external witness — the only thing that reports Sentinel's own death — goes
    silent, while every local check keeps saying the host is fine.
    """
    stdin = {k: HOST_SECRETS[k] for k in
             ("ANTHROPIC_API_KEY", "TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID",
              "TELEGRAM_APPLY_PIN")}
    stdin["SENTINEL_DB_PASSWORD"] = "NEW-db-password"

    out = run_step_secrets(tmp_path, HOST_SECRETS, stdin)
    assert out["proc"].returncode == 0, out["proc"].stderr

    assert set(out["keys"]) == set(HOST_SECRETS), (
        "keys lost: " + str(sorted(set(HOST_SECRETS) - set(out["keys"]))))
    assert out["keys"]["SENTINEL_DB_PASSWORD"] == "NEW-db-password"
    for key, value in HOST_SECRETS.items():
        if key == "SENTINEL_DB_PASSWORD":
            continue
        assert out["keys"][key] == value, f"{key} changed during a DB-password rotation"


def test_the_carried_keys_are_named_in_the_output(tmp_path):
    """The operator has to be able to see that it happened.

    The step already printed a green line about the keys it kept while deleting
    another one — an accurate sentence that produced a false impression. Names
    only; a value here would be a value in the deploy log.

    The key used here has to be one the installer genuinely does not manage.
    SENTINEL_BEACON_SECRET was that key until 19 August 2026, when it joined
    OPERATOR_SECRET_KEYS and stopped being carried at all — so a test still
    naming it would have gone green on a line that no longer proves anything.
    """
    host = dict(HOST_SECRETS, A_KEY_THIS_INSTALLER_NEVER_HEARD_OF="f" * 64)
    out = run_step_secrets(tmp_path, host, {})
    assert "A_KEY_THIS_INSTALLER_NEVER_HEARD_OF" in out["proc"].stdout
    assert "f" * 64 not in out["proc"].stdout + out["proc"].stderr
    assert out["keys"]["A_KEY_THIS_INSTALLER_NEVER_HEARD_OF"] == "f" * 64
    # And the value of a key it DOES manage stays out of the log too.
    assert "c" * 64 not in out["proc"].stdout + out["proc"].stderr


def test_an_unknown_key_is_not_regenerated_but_carried(tmp_path):
    """SENTINEL_BEACON_SECRET must match the watcher's copy. A fresh value is as
    broken as no value at all, and harder to notice: the beacon would sign
    happily and the watcher would reject every beat as a bad signature."""
    out = run_step_secrets(tmp_path, HOST_SECRETS, {})
    assert out["keys"]["SENTINEL_BEACON_SECRET"] == "c" * 64
    assert "FRESHLY-GENERATED" not in out["keys"].values()
    assert "rand -hex 32" not in out["calls"], "a key was minted when all eight existed"


