def test_in_list_does_not_match_a_prefix(tmp_path):
    """A loose match here deletes secrets.

    `in_list` decides whether a key found on disk is already known. With prefix
    matching, a host key called SENTINEL_SESSION is judged to be
    SENTINEL_SESSION_SECRET, is never added to the write order, and disappears
    from the rewritten file — the blocker's failure mode, restored.
    """
    script = tmp_path / "inlist.sh"
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(
        "source ./lib/common.sh\n"
        'for probe in SENTINEL_SESSION TELEGRAM_APPLY SENTINEL_SESSION_SECRET_X \n'
        "do\n"
        '  in_list "$probe" TELEGRAM_CALLBACK_HMAC_KEY SENTINEL_SESSION_SECRET '
        'TELEGRAM_APPLY_PIN && printf "MATCHED:%s\\n" "$probe"\n'
        "done\n"
        'in_list SENTINEL_SESSION_SECRET TELEGRAM_CALLBACK_HMAC_KEY '
        'SENTINEL_SESSION_SECRET && printf "EXACT-OK\\n"\n',
        encoding="utf-8", newline="\n")
    proc = subprocess.run([BASH, str(script).replace("\\", "/")],
                          cwd=REPO / "deploy", capture_output=True, text=True,
                          env={**os.environ, "NO_COLOR": "1"})
    assert "EXACT-OK" in proc.stdout, "exact membership no longer works at all"
    assert "MATCHED" not in proc.stdout, f"a non-member matched: {proc.stdout}"


