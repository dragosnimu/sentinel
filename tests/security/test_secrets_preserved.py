def test_only_the_generated_keys_may_be_created_from_nothing(tmp_path):
    """Minting a value for a key nobody set is worse than leaving it unset.

    TELEGRAM_APPLY_PIN is a PIN the operator types. Absent, the feature is off.
    Filled with 32 random bytes by the installer, patch apply starts demanding a
    PIN that exists nowhere except a 0640 file on the server — the operator is
    locked out of their own approval path and nothing in the run mentions it.
    Only the two host-generated keys are allowed to appear out of thin air.
    """
    on_disk = {k: v for k, v in HOST_SECRETS.items() if k != "TELEGRAM_APPLY_PIN"}
    out = run_step_secrets(tmp_path, on_disk, {})
    assert out["proc"].returncode == 0, out["proc"].stderr
    assert "TELEGRAM_APPLY_PIN" not in out["keys"], \
        f"a PIN was invented: {out['keys'].get('TELEGRAM_APPLY_PIN')!r}"
    assert "rand -hex 32" not in out["calls"]


def test_generated_keys_are_created_only_when_the_host_has_none(tmp_path):
    """A fresh host needs them; a host that has them must keep them, or every
    stored TOTP enrolment becomes undecryptable."""
    fresh = run_step_secrets(tmp_path / "a", None, {"SENTINEL_DB_PASSWORD": "x"})
    assert fresh["keys"]["SENTINEL_SESSION_SECRET"] == "FRESHLY-GENERATED"
    assert fresh["keys"]["TELEGRAM_CALLBACK_HMAC_KEY"] == "FRESHLY-GENERATED"

    again = run_step_secrets(tmp_path / "b", HOST_SECRETS, {})
    assert again["keys"]["SENTINEL_SESSION_SECRET"] == "b" * 64
    assert "rand -hex 32" not in again["calls"]


def test_an_upgrade_supplying_nothing_erases_nothing(tmp_path):
    """A re-deploy with no secrets on stdin — the documented upgrade path — must
    leave every value byte-identical."""
    out = run_step_secrets(tmp_path, HOST_SECRETS, {})
    assert out["keys"] == HOST_SECRETS


def test_the_mode_is_set_before_any_content_exists(tmp_path):
    """Writing first and chmod'ing after leaves a window in which every account
    on the host can read the file — a window that contains the API key, the bot
    token and the database password."""
    out = run_step_secrets(tmp_path, HOST_SECRETS, {})
    calls = [l for l in out["calls"].splitlines() if l.startswith("chmod")]
    assert calls, "the temp file is never chmod'ed"
    assert "0640" in calls[0], calls[0]
    assert calls[0].endswith("size=0"), f"mode set after content was written: {calls[0]}"


