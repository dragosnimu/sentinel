"""A re-run of step 27 must not delete a secret it does not know the name of.

`step_secrets` rebuilds /etc/sentinel/secrets.env from scratch on every run. It
used to fill the new file from two hard-coded lists — five operator keys and two
generated ones — and dropped everything else on the floor.

The host has eight keys. `SENTINEL_BEACON_SECRET` is the shared HMAC key between
Sentinel and the external watcher; it was added by hand after those lists were
written, it is not in secrets/.env.local, and it must never be regenerated
because the watcher holds the same value. So the documented password rotation,
`--force-step 22,27`, would have destroyed the only copy of it.

And nothing would have said so. This step prints a green line about the keys it
DID keep; `sentinel-beacon` exits 0 when the secret is missing, so `systemctl
restart` returns 0 and step 36 reports "enabled and restarted" over a dead unit.
The witness that exists to notice Sentinel's death would have gone quiet during
the procedure written to be safe.

These tests run the SHIPPED step 27 — declarations, `existing_secret` and
`step_secrets`, extracted verbatim between the `# --- 27` and `# --- 28` markers
— against a fabricated copy of the host's real key set.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = pytest.mark.security

REPO = Path(__file__).resolve().parents[2]
INSTALL_SH = REPO / "deploy" / "install.sh"
BASH = shutil.which("bash")

pytestmark = [pytest.mark.security,
              pytest.mark.skipif(BASH is None, reason="no bash on PATH")]

# The eight keys on the host. What matters is the NAMES — one of them is outside
# both of the installer's lists.
#
# The values are deliberately shaped so they cannot be mistaken for the real
# thing: test_repo_is_sanitised.py greps the whole tree for key-shaped strings,
# and a fixture that looks like an Anthropic key is exactly as much of a problem
# as a real one, because nobody triaging that finding can tell from the grep.
HOST_SECRETS = {
    "ANTHROPIC_API_KEY": "value-of-the-anthropic-key",
    "TELEGRAM_BOT_TOKEN": "value-of-the-bot-token",
    "TELEGRAM_CHAT_ID": "123456789",
    "SENTINEL_DB_PASSWORD": "OLD-db-password",
    "TELEGRAM_APPLY_PIN": "4242",
    "TELEGRAM_CALLBACK_HMAC_KEY": "a" * 64,
    "SENTINEL_SESSION_SECRET": "b" * 64,
    "SENTINEL_BEACON_SECRET": "c" * 64,
}


def step27_source() -> str:
    """Step 27 as shipped, not a copy of it.

    Extracted between the numbered section markers so the declarations travel
    with the functions. If the markers move, this raises rather than silently
    testing an empty string.
    """
    text = INSTALL_SH.read_text(encoding="utf-8")
    match = re.search(r"^# --- 27 -+\n(.*?)^# --- 28 -+$", text, re.S | re.M)
    assert match, "cannot find the step 27 block in install.sh"
    body = match.group(1)
    assert "step_secrets()" in body and "GENERATED_SECRET_KEYS" in body
    return body


HARNESS = """
source ./lib/common.sh
{step27}

# chown/chmod are stubbed: there is no `sentinel` user on a developer machine
# and modes do not survive this filesystem. The chmod stub records the SIZE of
# the file it is called on, which is what makes the ordering property testable:
# the mode has to be set while the file is still empty. Everything else here is
# the shipped code.
chown() {{ printf 'chown %s\\n' "$*" >> "$CALLS"; }}
chmod() {{ printf 'chmod %s size=%s\\n' "$*" "$(wc -c < "$2" 2>/dev/null || echo -1)" >> "$CALLS"; }}

# openssl is stubbed so that generation is OBSERVABLE. Asserting a value did not
# change is weaker than asserting no new one was ever minted.
#
# `rand -hex 32` mints a SECRET and must never happen when the host already has
# one; `rand -hex 16` mints the instance id, which step 27 does create on a
# fresh host by design. So the assertions below name the width rather than the
# binary, and this stub answers -hex 16 with something of the right SHAPE —
# `ensure_instance_id` re-reads the file and refuses anything else, and a stub
# that returned the placeholder for both would abort the step with a fatal
# error about the wrong thing.
openssl() {{
    printf 'openssl %s\\n' "$*" >> "$CALLS"
    if [[ "$*" == "rand -hex 16" ]]; then printf '0123456789abcdef0123456789abcdef'
    else printf 'FRESHLY-GENERATED'; fi
}}

declare -A SECRETS=({stdin})
step_secrets
"""


def run_step_secrets(tmp_path: Path, on_disk: dict[str, str] | None,
                     stdin: dict[str, str], extra_lines: str = "") -> dict:
    cfg = tmp_path / "etc"
    cfg.mkdir(parents=True, exist_ok=True)
    target = cfg / "secrets.env"
    if on_disk is not None:
        body = "# Generated by install.sh at 2026-07-31T00:00:00Z\n"
        body += "".join(f"{k}={v}\n" for k, v in on_disk.items())
        body += extra_lines
        target.write_text(body, encoding="utf-8")

    calls = tmp_path / "calls.txt"
    script = HARNESS.format(
        step27=step27_source(),
        stdin=" ".join(f"[{k}]={v!r}".replace("'", '"') for k, v in stdin.items()),
    )
    # Written to a file rather than passed to `bash -c`. On Windows the script
    # travels through CreateProcess's command line, and this one is large enough
    # and quoted heavily enough that it arrives mangled — bash then reports a
    # syntax error in code that is perfectly valid. A file has no such transit.
    script_path = tmp_path / "harness.sh"
    script_path.write_text(script, encoding="utf-8", newline="\n")
    proc = subprocess.run(
        [BASH, str(script_path).replace("\\", "/")],
        cwd=REPO / "deploy", capture_output=True, text=True,
        env={**os.environ, "NO_COLOR": "1",
             "SENTINEL_CONFIG_DIR": str(cfg).replace("\\", "/"),
             "SENTINEL_USER": "sentinel",
             "CALLS": str(calls).replace("\\", "/")},
    )
    written = {}
    if target.exists():
        for line in target.read_text(encoding="utf-8").splitlines():
            if line.startswith("#") or "=" not in line:
                continue
            k, _, v = line.partition("=")
            written[k] = v
    return {"proc": proc, "keys": written,
            "calls": calls.read_text(encoding="utf-8") if calls.exists() else ""}


# ---------------------------------------------------------------------------
# Reading stdin: a line that is not a key must not be treated as one
# ---------------------------------------------------------------------------
READER = """
source ./lib/common.sh
{reader}
for k in "${{!SECRETS[@]}}"; do printf 'KEY:%s=%s\\n' "$k" "${{SECRETS[$k]}}"; done
"""


def run_reader(tmp_path: Path, stdin_text: str) -> dict:
    """The shipped stdin block — declarations, reader and its warnings."""
    text = INSTALL_SH.read_text(encoding="utf-8")
    match = re.search(r"^declare -A SECRETS=\(\).*?^fi$", text, re.S | re.M)
    assert match, "cannot find the stdin secrets block in install.sh"
    assert "read_stdin_secrets" in match.group(0)

    script = tmp_path / "reader.sh"
    script.parent.mkdir(parents=True, exist_ok=True)
    script.write_text(READER.format(reader=match.group(0)), encoding="utf-8", newline="\n")
    # Bytes, not text=True. On Windows a text-mode pipe rewrites every \n as
    # \r\n, so an LF fixture would arrive as CRLF and the two cases below could
    # not be told apart — which is how the CRLF handling went unnoticed in the
    # first place: the harness was silently feeding CRLF to everything.
    proc = subprocess.run(
        [BASH, str(script).replace("\\", "/")],
        cwd=REPO / "deploy", capture_output=True,
        input=stdin_text.encode("utf-8"), env={**os.environ, "NO_COLOR": "1"},
    )
    stdout = proc.stdout.decode("utf-8", "replace")
    stderr = proc.stderr.decode("utf-8", "replace")
    parsed = {}
    for line in stdout.split("\n"):
        if line.startswith("KEY:"):
            k, _, v = line[4:].partition("=")
            parsed[k] = v
    return {"proc": proc, "out": stdout, "err": stderr, "keys": parsed}


def test_a_wrapped_value_never_becomes_a_key_name(tmp_path):
    """The leak, in the shape that produced it.

    An editor wrapped a value in secrets/.env.local, so the second line had no
    `=`. Read with `IFS='=' read -r key value`, that line became a KEY whose
    name was the tail of an API key — and the installer printed that name when
    it declined to write it. The tail landed on the operator's console and in
    the deploy log, which is a rotated key plus an incident.

    Line numbers, never content: on a malformed line the content is the secret.
    """
    tail = "EP0jRhaJInouJPfiFesxkXVVFlGspGPcIMknQR4ww-EIZJ-QAA"
    out = run_reader(tmp_path, f"ANTHROPIC_API_KEY=sk-first-part-of-the-value\n{tail}\n")
    combined = out["out"] + out["err"]

    assert tail not in combined, "secret material printed as a key name"
    assert list(out["keys"]) == ["ANTHROPIC_API_KEY"], out["keys"]
    assert "line(s): 2" in combined, f"the line number is not reported: {combined}"


def test_the_reader_still_reads_ordinary_secrets(tmp_path):
    """The guard must not eat the normal case: values with '=' in them, quoted
    values, blank lines and comments all have to survive."""
    out = run_reader(tmp_path, "\n".join([
        "# comment",
        "   # indented comment",
        "",
        "SENTINEL_DB_PASSWORD=abc=def==",
        'TELEGRAM_BOT_TOKEN="quoted-value"',
        "  INDENTED_KEY=indented",
    ]) + "\n")
    assert out["keys"]["SENTINEL_DB_PASSWORD"] == "abc=def=="
    assert out["keys"]["TELEGRAM_BOT_TOKEN"] == "quoted-value"
    assert out["keys"]["INDENTED_KEY"] == "indented"
    assert "line(s)" not in out["err"], "a valid file produced a warning"


def test_a_crlf_file_does_not_produce_a_password_the_daemons_cannot_use(tmp_path):
    """A secrets/.env.local saved by a Windows editor.

    The CR survived into the value, which defeated the trailing-quote strip, and
    that exact string went to `ALTER ROLE ... PASSWORD` and into secrets.env —
    while sentinel/config.py strips the line when the daemons read it. So every
    daemon would authenticate with a value one byte shorter than the one the
    database was given: a rotation that reports success and leaves Sentinel
    unable to reach its own database.

    Found because this harness was itself feeding CRLF on Windows without
    anybody asking it to.
    """
    line = 'SENTINEL_DB_PASSWORD="secret"'
    lf = run_reader(tmp_path / "lf", line + chr(10))
    crlf = run_reader(tmp_path / "crlf", line + chr(13) + chr(10))
    assert lf["keys"]["SENTINEL_DB_PASSWORD"] == "secret"
    assert crlf["keys"] == lf["keys"], "CRLF and LF must yield the same secret"
    # Handled, but said out loud: the operator's editor is doing something they
    # did not ask for, and that file is not covered by .gitattributes.
    assert "CRLF" in crlf["err"]
    assert "CRLF" not in lf["err"]


