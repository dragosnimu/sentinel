def test_a_key_only_stdin_knows_is_refused_out_loud(tmp_path):
    """A name the installer does not know is far more likely a typo in
    .env.local than a new secret, and writing it would make the typo look like a
    successful rotation. But the operator typed it on purpose, so dropping it
    silently is the same failure from the other direction.

    (This is a misuse guard, not a privilege boundary. Nothing loads secrets.env
    as an EnvironmentFile — sentinel/config.py reads it directly and looks up a
    fixed set of names. An earlier version of this docstring claimed otherwise,
    which is how a constraint nobody can check gets preserved forever.)
    """
    out = run_step_secrets(tmp_path, HOST_SECRETS,
                           {"LD_PRELOAD": "/tmp/evil.so", "SENTINEL_DB_PASSWORD": "NEW"})
    assert "LD_PRELOAD" not in out["keys"]
    assert "LD_PRELOAD" in out["proc"].stderr
    assert out["keys"]["SENTINEL_DB_PASSWORD"] == "NEW"


def test_a_key_already_on_the_host_may_be_updated_from_stdin(tmp_path):
    """The refusal above is about names, not about values: a name the host
    already has was put there by root, so rotating it through the deploy channel
    is allowed. Otherwise the beacon key could never be rotated at all, and the
    installer would ignore a value the operator explicitly supplied."""
    out = run_step_secrets(tmp_path, HOST_SECRETS,
                           {"SENTINEL_BEACON_SECRET": "d" * 64})
    assert out["keys"]["SENTINEL_BEACON_SECRET"] == "d" * 64


def test_a_shared_key_lands_on_a_host_that_never_had_it(tmp_path):
    """The failure this prevents: a second server is installed, the operator
    supplies SENTINEL_SHIP_SECRET through the deploy channel, and the installer
    drops it as an unknown name. Everything reports success -- the unit is
    enabled, the process starts, and `ship` exits 0 when the secret is missing
    -- so the only symptom is a panel that never gains that instance's data,
    discovered whenever somebody happens to look.

    HOST_SECRETS has no ship key, so this is the FIRST placement, not a
    rotation. That is the case the carry-forward rule cannot cover, because
    there is nothing yet to carry."""
    out = run_step_secrets(tmp_path, HOST_SECRETS,
                           {"SENTINEL_SHIP_SECRET": "e" * 64})
    assert out["keys"]["SENTINEL_SHIP_SECRET"] == "e" * 64, (
        "the ship key was dropped as an unknown name; a new host cannot be "
        "given one through the reviewed path")
    assert "SENTINEL_SHIP_SECRET" not in out["proc"].stderr, (
        "the key landed but was also reported as refused")
    # The keys already on the host are untouched by the new name.
    assert out["keys"]["SENTINEL_BEACON_SECRET"] == "c" * 64
    assert out["keys"]["SENTINEL_SESSION_SECRET"] == "b" * 64


def test_a_shared_key_nobody_supplied_is_not_written_empty(tmp_path):
    """Adding names to OPERATOR_SECRET_KEYS must not create empty lines.

    `sentinel/config.py:load_secrets` reads this file directly. A line
    `SENTINEL_SHIP_SECRET=` is a key that EXISTS with no value, which reads as
    configured-but-broken rather than absent -- and the two get different
    diagnoses from anyone reading the file."""
    out = run_step_secrets(tmp_path, HOST_SECRETS, {})
    assert "SENTINEL_SHIP_SECRET" not in out["keys"], (
        "a key nobody supplied was written anyway")
    body = (tmp_path / "etc" / "secrets.env").read_text(encoding="utf-8")
    assert "SENTINEL_SHIP_SECRET=" not in body


def test_a_malformed_name_is_never_printed_even_if_it_reaches_this_step(tmp_path):
    """The second lock on the door the stdin reader now closes.

    The refusal message prints the key name. If anything ever puts a malformed
    "name" into SECRETS again — which is exactly what reading with IFS='=' did
    to a wrapped value — that message would publish secret material. The name is
    only printed once it looks like a name.
    """
    tail = "EP0jRhaJInouJPfiFesxkXVVFlGspGPcIMknQR4ww-EIZJ-QAA"
    out = run_step_secrets(tmp_path, HOST_SECRETS, {tail: ""})
    combined = out["proc"].stdout + out["proc"].stderr
    assert tail not in combined, "a malformed key name was printed verbatim"
    assert "withheld" in combined, "the refusal is not reported at all"


def test_a_carried_key_with_an_empty_value_is_kept_not_just_counted(tmp_path):
    """Reporting a key as carried and then dropping it is intent-as-effect.

    The green line named it; the value was empty, so the write was skipped, and
    the key vanished. It also makes the key-name diff in OPERARE.md §11 (a) —
    the check that proves nothing was lost — report a loss on a healthy run.
    """
    on_disk = dict(HOST_SECRETS, AN_UNKNOWN_KEY_ON_DISK="")
    out = run_step_secrets(tmp_path, on_disk, {})
    assert out["proc"].returncode == 0, out["proc"].stderr
    assert "AN_UNKNOWN_KEY_ON_DISK" in out["proc"].stdout, "not even reported"
    assert "AN_UNKNOWN_KEY_ON_DISK" in out["keys"], \
        "named as carried over, then dropped from the file"
    assert set(out["keys"]) == set(on_disk)


def test_an_indented_comment_is_a_comment(tmp_path):
    """`   # notă` triggered "recover them from a backup if they mattered" — a
    warning that must only ever mean "you lost a secret". Cry wolf once and the
    real one is read as the same noise."""
    out = run_step_secrets(tmp_path, HOST_SECRETS, {},
                           extra_lines="   # o notă a operatorului\n")
    combined = out["proc"].stdout + out["proc"].stderr
    assert "backup" not in combined, combined
    assert set(out["keys"]) == set(HOST_SECRETS)


def test_an_indented_key_keeps_its_value(tmp_path):
    """sentinel/config.py strips before parsing, so an indented key WORKS today.

    The installer must therefore read it the same way. If the scan accepts the
    key but the value lookup does not, the key survives with an empty value —
    a deletion that passes the key-name diff, which is the worst kind.
    """
    out = run_step_secrets(tmp_path, HOST_SECRETS, {},
                           extra_lines="  INDENTED_KEY=indented-value\n")
    assert out["keys"].get("INDENTED_KEY") == "indented-value"


def test_an_unparseable_line_is_reported_by_line_number(tmp_path):
    """It cannot be carried over, so it has to be announced. The old file is
    replaced; an operator who is not told loses whatever was on that line
    without ever learning it existed. The number, never the content — this file
    is nothing but secrets."""
    out = run_step_secrets(tmp_path, HOST_SECRETS, {},
                           extra_lines="this line is not KEY=value\n")
    combined = out["proc"].stdout + out["proc"].stderr
    assert "10" in combined and "line" in combined.lower()
    assert "this line is not" not in combined
